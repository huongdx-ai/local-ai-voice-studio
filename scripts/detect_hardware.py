def main():
    print("=" * 60)
    print(" Local AI Voice Studio - Hardware Detection")
    print("=" * 60)
    print()

    cpu = detect_cpu()
    ram = detect_ram()
    nvidia = detect_nvidia()
    capability = detect_cuda_capability()

    backend = choose_backend(nvidia)

    config = {
        "cpu": cpu,
        "ram_gb": ram,
        "gpu_name": nvidia["name"],
        "vram_gb": nvidia["vram_gb"],
        "nvidia_driver": nvidia["driver"],
        "cuda_compute_capability": capability,
        "backend": backend["backend"],
        "torch_version": backend["torch_version"],
        "torchaudio_version": backend["torchaudio_version"],
        "torch_index_url": backend["torch_index_url"],
    }

    print(f"CPU:             {cpu}")
    print(f"RAM:             {ram} GB")

    if nvidia["available"]:
        print(f"GPU:             {nvidia['name']}")
        print(f"VRAM:            {nvidia['vram_gb']} GB")
        print(f"NVIDIA Driver:   {nvidia['driver']}")

        if capability:
            print(f"Compute Cap:     {capability}")

        print()
        print("Backend:          NVIDIA CUDA")
        print(f"PyTorch:         {backend['torch_version']}")
        print("CUDA Runtime:    12.4")

    else:
        print("GPU:             None / NVIDIA GPU not detected")
        print()
        print("Backend:          CPU")
        print(f"PyTorch:         {backend['torch_version']}")

    print()
    print("Generating requirements.txt...")

    generate_requirements(config)

    print(f"Generated: {REQUIREMENTS_FILE}")

    # Save hardware configuration
    config_file = PROJECT_ROOT / "hardware_config.json"

    config_file.write_text(
        json.dumps(config, indent=2),
        encoding="utf-8",
    )

    print(f"Hardware config: {config_file}")

    print()
    print("=" * 60)
    print(" Hardware Detection Complete")
    print("=" * 60)


