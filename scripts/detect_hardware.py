import json
import platform
import re
import subprocess
import sys
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS_FILE = PROJECT_ROOT / "backend" / "requirements.txt"


def run_command(command):
    try:
        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=10,
            shell=False,
        )

        if result.returncode == 0:
            return result.stdout.strip()

    except Exception:
        pass

    return None


def detect_cpu():
    cpu = platform.processor()

    if not cpu:
        cpu = "Unknown CPU"

    return cpu


def detect_ram():
    try:
        import psutil

        return round(psutil.virtual_memory().total / (1024 ** 3), 1)

    except Exception:
        return None


def detect_nvidia():
    """
    Detect NVIDIA GPU using nvidia-smi.

    This works BEFORE PyTorch is installed.
    """

    output = run_command(
        [
            "nvidia-smi",
            "--query-gpu=name,memory.total,driver_version",
            "--format=csv,noheader,nounits",
        ]
    )

    if not output:
        return {
            "available": False,
            "name": None,
            "vram_gb": None,
            "driver": None,
        }

    line = output.splitlines()[0]

    parts = [x.strip() for x in line.split(",")]

    if len(parts) < 3:
        return {
            "available": False,
            "name": None,
            "vram_gb": None,
            "driver": None,
        }

    name = parts[0]

    try:
        vram_mb = float(parts[1])
        vram_gb = round(vram_mb / 1024, 1)
    except Exception:
        vram_gb = None

    driver = parts[2]

    return {
        "available": True,
        "name": name,
        "vram_gb": vram_gb,
        "driver": driver,
    }


def detect_cuda_capability():
    """
    RTX 3060 Ti / RTX 30 series:
    Compute Capability = 8.6

    This function tries to get the capability from an existing
    CUDA-enabled PyTorch installation.
    """

    try:
        import torch

        if torch.cuda.is_available():
            capability = torch.cuda.get_device_capability(0)

            return f"{capability[0]}.{capability[1]}"

    except Exception:
        pass

    return None


def choose_backend(nvidia):
    if nvidia["available"]:
        return {
            "backend": "cuda",
            "torch_version": "2.6.0+cu124",
            "torchaudio_version": "2.6.0+cu124",
            "torch_index_url": "https://download.pytorch.org/whl/cu124",
        }

    return {
        "backend": "cpu",
        "torch_version": "2.6.0",
        "torchaudio_version": "2.6.0",
        "torch_index_url": "https://download.pytorch.org/whl/cpu",
    }


